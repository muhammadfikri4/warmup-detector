#!/bin/zsh
# Writes Config/Local.xcconfig (git-ignored) so this Mac builds with YOUR bundle ID prefix and Apple team.
# Usage: ./scripts/setup-signing.sh <bundle-id-prefix> [team-id]
#   e.g. ./scripts/setup-signing.sh albertus
# Without team-id, it is read from the "Apple Development" certificate in your keychain
# (sign in to Xcode → Settings → Accounts once so the certificate exists).
set -euo pipefail
cd "$(dirname "$0")/.."
PREFIX=${1:?"Usage: $0 <bundle-id-prefix> [team-id]   e.g. $0 albertus"}
TEAM=${2:-}
if [[ -z "$TEAM" ]]; then
  TEAMS=($(security find-certificate -a -c "Apple Development" -p 2>/dev/null \
    | awk '/BEGIN CERT/{c=""} {c=c $0 "\n"} /END CERT/{print c | "openssl x509 -noout -subject -nameopt multiline"; close("openssl x509 -noout -subject -nameopt multiline")}' \
    | awk -F'= ' '/organizationalUnitName/ {print $2}' | sort -u))
  if (( ${#TEAMS} == 0 )); then
    echo "No Apple Development certificate found. Open Xcode → Settings → Accounts, add your Apple ID, then rerun (or pass the team ID)."; exit 1
  elif (( ${#TEAMS} > 1 )); then
    echo "Several teams found: ${TEAMS[*]} — rerun with one: $0 $PREFIX <team-id>"; exit 1
  fi
  TEAM=${TEAMS[1]}
fi
cat > Config/Local.xcconfig <<CFG
// Generated by scripts/setup-signing.sh — git-ignored, per developer.
BUNDLE_ID_PREFIX = $PREFIX
DEVELOPMENT_TEAM = $TEAM
CFG
echo "Config/Local.xcconfig → prefix $PREFIX, team $TEAM"
echo "Bundle IDs: $PREFIX.warmuppulse (iPhone), $PREFIX.warmuppulse.watchkitapp (Watch)"
